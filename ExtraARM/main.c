// Expected output of layer 8 for my_asl_alexnet_small given the sample input (known-answer test)
// Delete this function for production code
static const uint32_t sample_output[] = SAMPLE_OUTPUT;
int check_output(void)
{
  int i;
  uint32_t mask, len;
  volatile uint32_t *addr;
  const uint32_t *ptr = sample_output;

  while ((addr = (volatile uint32_t *) *ptr++) != 0) {
    mask = *ptr++;
    len = *ptr++;
    for (i = 0; i < len; i++)
      if ((*addr++ & mask) != *ptr++) {
        printf("Data mismatch (%d/%d) at address 0x%08x: Expected 0x%08x, read 0x%08x.\n",
               i + 1, len, addr - 1, *(ptr - 1), *(addr - 1) & mask);
        return CNN_FAIL;
      }
  }

  return CNN_OK;
}

// Classification layer:
static int32_t ml_data[CNN_NUM_OUTPUTS];
static q15_t ml_softmax[CNN_NUM_OUTPUTS];

void softmax_layer(void)
{
  cnn_unload((uint32_t *) ml_data);
  softmax_q17p14_q15((const q31_t *) ml_data, CNN_NUM_OUTPUTS, ml_softmax);
}

int main(void)
{
  int i;
  int digs, tens;

  MXC_ICC_Enable(MXC_ICC0); // Enable cache

  // Switch to 100 MHz clock
  MXC_SYS_Clock_Select(MXC_SYS_CLOCK_IPO);
  SystemCoreClockUpdate();

  printf("\n*** CNN Inference Test - 32x32 Model (ARM) ***\n");
  printf("System Configuration:\n");
  printf("  Core:        ARM Cortex-M4 @ 100 MHz\n");
  printf("  CNN Clock:   50 MHz (APB div 1)\n");
  printf("  Image Size:  32x32 RGB\n\n");

  // Initialize energy measurement GPIO pins
  energy_measurement_init();

  printf("Waiting for debugger...\n");

  // DO NOT DELETE THIS LINE:
  MXC_Delay(SEC(2)); // Let debugger interrupt if needed

  /* ========== START TOTAL ENERGY MEASUREMENT ========== */
  energy_marker_total_high();
  uint32_t start_total = MXC_TMR_GetCount(MXC_TMR0);
  /* ==================================================== */

  // Enable peripheral, enable CNN interrupt, turn on CNN clock
  // CNN clock: APB (50 MHz) div 1
  cnn_enable(MXC_S_GCR_PCLKDIV_CNNCLKSEL_PCLK, MXC_S_GCR_PCLKDIV_CNNCLKDIV_DIV1);

  printf("Loading weights and configuring CNN...\n");
  
  /* Measure weight loading time */
  MXC_TMR_SW_Start(MXC_TMR1);
  cnn_init(); // Bring state machine into consistent state
  cnn_load_weights(); // Load kernels
  cnn_load_bias();
  cnn_configure(); // Configure state machine
  t_load_weights = MXC_TMR_SW_Stop(MXC_TMR1);

  /* Measure input loading time */
  printf("Starting CNN and loading input data...\n");
  MXC_TMR_SW_Start(MXC_TMR1);
  cnn_start(); // Start CNN processing
  load_input(); // Load data input via FIFO
  t_load_input = MXC_TMR_SW_Stop(MXC_TMR1);

  /* ========== START CNN-ONLY MEASUREMENT ========== */
  energy_marker_cnn_high();
  /* ================================================= */

  printf("Waiting for CNN inference to complete...\n");
  while (cnn_time == 0)
    MXC_LP_EnterSleepMode(); // Wait for CNN
  
  t_inference = cnn_time;

  /* ========== STOP CNN-ONLY MEASUREMENT ========== */
  energy_marker_cnn_low();
  /* ================================================ */

  printf("Validating output...\n");
  if (check_output() != CNN_OK) fail();
  
  /* Measure unload time */
  MXC_TMR_SW_Start(MXC_TMR1);
  cnn_unload((uint32_t *) ml_data);
  t_unload = MXC_TMR_SW_Stop(MXC_TMR1);
  
  /* Measure softmax time */
  MXC_TMR_SW_Start(MXC_TMR1);
  softmax_q17p14_q15((const q31_t *) ml_data, CNN_NUM_OUTPUTS, ml_softmax);
  t_softmax = MXC_TMR_SW_Stop(MXC_TMR1);

  /* ========== STOP TOTAL ENERGY MEASUREMENT ========== */
  t_total = MXC_TMR_GetCount(MXC_TMR0) - start_total;
  energy_marker_total_low();
  /* ==================================================== */

  printf("\n*** PASS ***\n");

  cnn_disable(); // Shut down CNN clock, disable peripheral

  /* Print detailed timing and energy measurement info */
  print_energy_timing();

  /* Print detailed timing and energy measurement info */
  print_energy_timing();

  printf("Classification Results:\n");
  printf("========================================================\n");
  for (i = 0; i < CNN_NUM_OUTPUTS; i++) {
    digs = (1000 * ml_softmax[i] + 0x4000) >> 15;
    tens = digs % 10;
    digs = digs / 10;
    printf("  Class %2d: %3d.%d%% [raw: %7d]\n", i, digs, tens, ml_data[i]);
  }
  printf("========================================================\n");

  return 0;
}

